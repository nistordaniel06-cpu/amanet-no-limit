'use strict';
const calc=require('../js/calculators.js');
let checks=0;
function equal(actual,expected,label){checks++;if(JSON.stringify(actual)!==JSON.stringify(expected))throw new Error(label+': '+JSON.stringify(actual)+' != '+JSON.stringify(expected));}
equal(calc.gold(10,324),3240,'10g 14K pawn');
equal(calc.gold(10,341),3410,'10g 14K sale');
equal(calc.gold(.1,194.1),19.41,'fractional gram');
equal(calc.gold(10.1,437.2),4415.72,'currency rounding');
for(const value of ['',null,undefined,-1,0,'abc',Infinity,10001])equal(calc.gold(value,324),null,'invalid gold weight '+value);
for(const value of ['',null,undefined,-1,0,'abc',Infinity])equal(calc.gold(10,value),null,'invalid gold rate '+value);
equal(calc.loan(1000,30,.5).commission,150,'gold commission');
equal(calc.loan(1000,30,.5).total,1150,'gold total');
equal(calc.loan(1000,30,.8).total,1240,'goods total');
equal(calc.loan(100.01,1,.5).total,100.51,'cents retained');
equal(calc.loan(1000000,365,.8).total,3920000,'upper valid boundary');
equal(calc.loan(100,1,0).total,100,'zero commission');
for(const value of ['',null,undefined,-1,0,99,'abc',Infinity,1000001])equal(calc.loan(value,30,.5),null,'invalid principal '+value);
for(const value of ['',null,undefined,0,-1,1.5,366,'abc',Infinity])equal(calc.loan(1000,value,.5),null,'invalid days '+value);
equal(calc.dueDate('2026-09-09',30),'2026-10-09','calendar date');
equal(calc.dueDate('2026-03-28',2),'2026-03-30','DST boundary');
equal(calc.dueDate('2028-02-28',1),'2028-02-29','leap year');
equal(calc.dueDate('2026-12-31',1),'2027-01-01','year boundary');
equal(calc.dueDate('2026-02-30',1),null,'invalid date');
equal(calc.dueDate('2026-09-09',0),null,'invalid date duration');
console.log(checks+' calculator assertions passed');
